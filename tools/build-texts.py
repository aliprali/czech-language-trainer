#!/usr/bin/env python3
import re
from pathlib import Path

texts_dir = Path(__file__).resolve().parent.parent / "data" / "texts"
out_file = Path(__file__).resolve().parent.parent / "data" / "texts.js"

if not texts_dir.exists():
    print(f"✗ Složka {texts_dir} neexistuje.")
    exit(1)

js_files = sorted(texts_dir.glob("*.js"))
if not js_files:
    print(f"✗ Ve složce {texts_dir} nejsou žádné .js soubory.")
    exit(1)

var_names = []
script_tags = []

for file in js_files:
    content = file.read_text(encoding="utf-8")
    # Najde proměnnou na začátku souboru, např. "const TEXT_KOMETA ="
    match = re.search(r'const\s+([A-Za-z0-9_]+)\s*=\s*\{', content)
    if match:
        var_name = match.group(1)
        var_names.append(var_name)
        script_tags.append(f'<script src="data/texts/{file.name}"></script>')
    else:
        print(f"⚠ Varování: V souboru {file.name} nebyla nalezena proměnná 'const ... ='.")

# Vygeneruje data/texts.js
js_content = "// AUTO-GENERATED by tools/build-texts.py. Do not edit manually.\n"
js_content += f"const TEXTS = [{', '.join(var_names)}];\n"
out_file.write_text(js_content, encoding="utf-8")

print(f"✓ Úspěšně nalezeno {len(var_names)} textů.")
print(f"✓ Vygenerováno {out_file}")
print("\n--- Zkopíruj tyto <script> tagy do index.html (před data/texts.js) ---")
for tag in script_tags:
    print(tag)
print('<script src="data/texts.js"></script>')